    @Test
    public void PRD_ADD_02_ProductCodeAutoGenerated() {
        loginAsAdmin();
        ProductPage productPage = new ProductPage();
        productPage.openProductPage();

        String codeBefore = productPage.getLastProductCode();

        productPage.clickAddProduct();
        productPage.fillProductForm("SP Auto Code Test", "250mg", "Gói", "30000", "Hoạt động");
        productPage.clickSubmit();

        productPage.isSuccessMessageDisplayed(); // chờ toast

        String codeAfter = productPage.getLastProductCode();

        Assert.assertNotEquals(codeBefore, codeAfter,
                "PRD_ADD_02 FAIL: Mã sản phẩm không được tự sinh sau khi thêm mới"
        );
        Assert.assertTrue(
                codeAfter.matches("SP\\d+"),
                "PRD_ADD_02 FAIL: Mã sản phẩm không đúng định dạng SPxxx. Thực tế: " + codeAfter
        );
    }

