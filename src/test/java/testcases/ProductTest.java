    // Kết quả mong đợi: Hiển thị "Cập nhật sản phẩm thất bại"
    // ----------------------------------------------------------------
    @Test(priority = 9)
    public void PRD_UPD_09_SystemErrorOnUpdate() throws InterruptedException {
        ProductPage productPage = openProductPageAsAdmin();
        productPage.clickEditFirstProduct();

        productPage.updateProductInfo("Tên test lỗi mạng", "50000");

        // Giả lập mất kết nối mạng bằng JS
        String mockScript = "var origFetch = window.fetch; window.fetch = async function(...args) { return Promise.reject(new TypeError('Failed to fetch')); }; "
                + "var origOpen = XMLHttpRequest.prototype.open; XMLHttpRequest.prototype.open = function(method, url) { this._interceptUrl = url; origOpen.apply(this, arguments); }; "
                + "var origSend = XMLHttpRequest.prototype.send; XMLHttpRequest.prototype.send = function(body) { var self = this; setTimeout(function() { if (self.onerror) self.onerror(new ProgressEvent('network error')); }, 100); return; origSend.apply(this, arguments); };";
        ((org.openqa.selenium.JavascriptExecutor) driver).executeScript(mockScript);

        productPage.clickSubmit();

        Thread.sleep(1500);
        String msg = productPage.getToastMessage().toLowerCase();
        Assert.assertTrue(
                msg.contains("thất bại") || msg.contains("lỗi"),
                "PRD_UPD_09 FAIL: Không hiển thị thông báo 'Cập nhật sản phẩm thất bại' khi mất kết nối mạng!"
        );
    }

    // ================================================================
    //  Helper
    // ================================================================
    private ProductPage openProductPageAsAdmin() {
        login(Constant.ADMIN_USER, Constant.ADMIN_PASS);

        wait.until(ExpectedConditions.elementToBeClickable(
                By.xpath("//nav//a[contains(@href,'/products')]")
        )).click();

        wait.until(ExpectedConditions.or(
                ExpectedConditions.visibilityOfElementLocated(By.xpath("//*[contains(text(),'Quản lý sản phẩm')]")),
                ExpectedConditions.visibilityOfElementLocated(By.xpath("//button[contains(.,'Thêm sản phẩm')]")),
                ExpectedConditions.visibilityOfElementLocated(By.xpath("//*[contains(text(),'SP')]"))
        ));

        return new ProductPage(driver);
    }

    private void loginAsAdmin() {
        login(Constant.ADMIN_USER, Constant.ADMIN_PASS);
    }
