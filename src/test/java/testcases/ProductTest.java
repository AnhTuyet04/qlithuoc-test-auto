    @Test
    public void PRD_ADD_01_AddProductSuccessfully() {
        loginAsAdmin();
        ProductPage productPage = new ProductPage();
        productPage.openProductPage();
        productPage.clickAddProduct();

        String productName = "Thuốc Test Auto " + System.currentTimeMillis();
        productPage.fillProductForm(productName, "500mg", "Viên", "50000", "Hoạt động");
        productPage.clickSubmit();

        Assert.assertTrue(
                productPage.isSuccessMessageDisplayed(),
                "PRD_ADD_01 FAIL: Không hiển thị thông báo thêm sản phẩm thành công"
        );
        Assert.assertTrue(
                productPage.isProductInTable(productName),
                "PRD_ADD_01 FAIL: Sản phẩm mới không xuất hiện trong danh sách"
        );
    }

